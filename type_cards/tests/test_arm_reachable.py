"""The arm card's coverage counts over the cells a mounted arm can reach, not over the joint box (2026-11-05,
docs/decision-arm-reachable-coverage-2026-11-05.md). Written before the code.

The servo's denominator is its reachable rule (coverage.joint_reachable: a cell counts when the joint can hold its centre).
The arm's is a committed mask per mount (type_cards/arm_reachable/<mount>.json): a joint-cube cell counts when a collision-free
configuration of the mounted arm lies inside it, with the shoulder lift inside the span connected to the arm's home posture.
The mask is generated by tools/arm_reachable.py from MuJoCo's own collision check (sysid.arm.Clearance) and a fixed scrambled
Sobol probe per cell; sysid/tests/test_arm_reachable_mask.py regenerates it and holds the committed file to it. Here (stdlib,
no MuJoCo) the file's integrity and the card's use of it are held.

    python3 -m pytest -q -p no:cacheprovider /home/bam/sim2real/type_cards/tests/test_arm_reachable.py
"""

from __future__ import annotations

import hashlib
import itertools
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from type_cards import coverage as cov  # noqa: E402
from type_cards import registry as reg  # noqa: E402

MASKS = ROOT / "type_cards" / "arm_reachable"
CUBE = cov.JOINT_BINS ** 6
LIFT = 1  # the shoulder lift's axis in the joint cube


def mask_doc(mount: str) -> dict:
    return json.loads((MASKS / f"{mount}.json").read_text())


def cells_of(doc: dict) -> set:
    order = itertools.product(range(cov.JOINT_BINS), repeat=6)
    return {cell for cell, bit in zip(order, doc["mask"]) if bit == "1"}


def centre(cell) -> tuple:
    edges = [[lo + (hi - lo) * i / cov.JOINT_BINS for i in range(cov.JOINT_BINS + 1)] for lo, hi in cov.UR5E_LIMITS]
    return tuple(0.5 * (edges[j][i] + edges[j][i + 1]) for j, i in enumerate(cell))


def test_every_mount_has_a_whole_self_consistent_mask():
    assert set(cov.ARM_MOUNTS) == {"ur5e_floor", "ur5e_2f85_floor"} and cov.DEFAULT_ARM_MOUNT == "ur5e_floor"
    for mount in cov.ARM_MOUNTS:
        doc = mask_doc(mount)
        assert doc["mount"] == mount and len(doc["mask"]) == CUBE and set(doc["mask"]) <= {"0", "1"}, mount
        assert doc["reachable"] == doc["mask"].count("1"), mount
        assert doc["sha256"] == hashlib.sha256(doc["mask"].encode()).hexdigest(), mount
        assert [list(x) for x in doc["limits"]] == [list(x) for x in cov.UR5E_LIMITS] and doc["joint_bins"] == cov.JOINT_BINS, mount
        assert doc["generator"] == "tools/arm_reachable.py", mount
        assert cells_of(doc) == cov.arm_reachable_cells(mount), mount


def test_the_masks_hold_what_the_ur_lane_measured():
    """The lane's finding, now the ruler: the shoulder lift's bin 3 is bin 1 shifted 2 pi and unreachable from home (empty),
    bin 1 (the arm above its mount) is whole, bins 0 and 2 hold only cells whose lift slice meets the span connected to home."""
    for mount in cov.ARM_MOUNTS:
        doc = mask_doc(mount)
        cells = cells_of(doc)
        by_lift = [sum(1 for c in cells if c[LIFT] == b) for b in range(cov.JOINT_BINS)]
        assert by_lift[3] == 0, (mount, by_lift)
        assert by_lift[1] == CUBE // cov.JOINT_BINS, (mount, by_lift)
        lo, hi = doc["lift_span_rad"]
        assert lo < -math.pi < -1.2 < 0 < hi < math.pi / 2, (mount, doc["lift_span_rad"])  # home (-1.2) inside; a sliver past each horizontal
        assert 0.4 * CUBE < doc["reachable"] < 0.75 * CUBE, (mount, doc["reachable"])


def test_the_arm_cards_coverage_counts_over_its_mounts_reachable_cells():
    card = reg.CARDS["arm_6dof"]
    assert card.coverage.reachable_mask == "ur5e_floor"
    assert reg.CARDS["arm_6dof_gripper"].coverage.reachable_mask == "ur5e_2f85_floor"
    reach = sorted(cov.arm_reachable_cells("ur5e_floor"))
    unreachable = [c for c in itertools.product(range(cov.JOINT_BINS), repeat=6) if c[LIFT] == 3][:50]
    points = [{"joint space": centre(c)} for c in reach[:300]] + [{"joint space": centre(c)} for c in unreachable]
    r = card.coverage.measure(points)
    assert r.reachable == len(reach) and r.visited == 300, (r.reachable, r.visited)
    assert r.pct == round(100.0 * 300 / len(reach), 2)
    # the same points on the 2F-85's mask: its own denominator
    g = card.coverage.measure(points, mount="ur5e_2f85_floor")
    assert g.reachable == len(cov.arm_reachable_cells("ur5e_2f85_floor"))


def test_the_gate_is_a_share_of_the_reachable_cells():
    """40 % of the reachable cells (the servo's promise, unchanged GATE_PCT), not of the 4,096-cell box."""
    card = reg.CARDS["arm_6dof"]
    assert card.coverage.gate_pct == 40.0
    reach = sorted(cov.arm_reachable_cells("ur5e_floor"))
    need = math.ceil(card.coverage.gate_pct / 100.0 * len(reach))
    passing = card.coverage.measure([{"joint space": centre(c)} for c in reach[:need]])
    failing = card.coverage.measure([{"joint space": centre(c)} for c in reach[: need - 1]])
    assert reg.coverage_gate(card, passing) == "pass" and reg.coverage_gate(card, failing) == "fail"
    assert need < 0.4 * CUBE  # looser in cells than the box's 1,639: the box's half that no floor-mounted arm reaches is out


def test_arm_coverage_without_a_mount_is_unchanged():
    """Additive only: cov.arm_coverage(points) and the sub-assembly's 3-joint box still count every cell."""
    r = cov.arm_coverage([{"joint space": (0.0,) * 6}])
    assert r.reachable == CUBE and r.visited == 1
    sub = reg.CARDS["arm_subassembly"].coverage.measure([{"joint space": (0.0, 0.0, 0.0)}])
    assert sub.reachable == cov.JOINT_BINS ** 3 and reg.CARDS["arm_subassembly"].coverage.reachable_mask is None


def test_the_export_names_the_mask():
    cards = {c["id"]: c for c in reg.export()["cards"]}
    assert cards["arm_6dof"]["coverage"]["reachable_mask"] == "ur5e_floor"
    assert cards["servo"]["coverage"]["reachable_mask"] is None
